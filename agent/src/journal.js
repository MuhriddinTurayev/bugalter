import { PORTAL_ORIGIN } from './config.js';
import { dismissNotice, settle } from './discover.js';
import { isReportingOpen } from './login.js';
import { NotMapped } from './cabinet.js';
import { readTable } from './tables.js';

// The e-reporting journal of oldmy.soliq.uz (wefo4-clientui), as observed on 2026-10-24:
//  - it is reached by clicking a service card on my.soliq.uz/with-sidebar/services (a new tab opens, with single sign-on);
//  - the journal page has one pane per state: #div_processing_reports, #div_error_reports, #div_approved_reports,
//    #div_sent_reports, #div_rejected_reports, #div_draft_reports, #div_scheduled_reports; every pane is in the DOM
//    all the time, each with a Bootstrap table whose headers are Russian (see COLUMNS).

/** Pane id -> the state its rows are in, as Bugalter's PortalSnapshot understands it. */
export const PANES = {
  div_processing_reports: 'submitted', // being checked by the tax authority
  div_sent_reports: 'submitted',
  div_approved_reports: 'accepted', // "Принятые"; the state column says e.g. "Проведенный с опозданием"
  div_error_reports: 'rejected', // "С ошибками"
  div_rejected_reports: 'rejected', // "Отказанные"
  div_draft_reports: 'draft',
  div_scheduled_reports: 'draft', // "Автомат": generated by the tax authority, not filed by the taxpayer yet
};

const COLUMNS = {
  report_id: /№\s*Отчета/i,
  form: /Наименование/i,
  year: /^Год$/i,
  period: /^Период$/i,
  sent_at: /Дата отправки/i,
  state: /Состояние/i,
};

const MONTHS = ['январь', 'февраль', 'март', 'апрель', 'май', 'июнь', 'июль', 'август', 'сентябрь', 'октябрь', 'ноябрь', 'декабрь'];

/** "Сентябрь" + "2026" -> {start, end} as Y-m-d, or null for wording that was not observed (quarters, half-years...). */
export function periodOf(periodText, yearText) {
  const month = MONTHS.indexOf(String(periodText).trim().toLowerCase());
  const year = /^\d{4}$/.test(String(yearText).trim()) ? Number(yearText) : null;
  if (month < 0 || year === null) return null;

  const pad = (n) => String(n).padStart(2, '0');
  const last = new Date(Date.UTC(year, month + 1, 0)).getUTCDate();
  return { start: `${year}-${pad(month + 1)}-01`, end: `${year}-${pad(month + 1)}-${pad(last)}` };
}

/** Bugalter's report type for a form's name, from the names the system itself uses; null when unknown (never guessed). */
export function typeOf(formName, table) {
  const name = String(formName).toLowerCase();
  for (const [needle, type] of Object.entries(table ?? {})) if (name.includes(needle.toLowerCase())) return type;
  return null;
}

/** dd.mm.yyyy [hh:mm] -> Y-m-d */
const dateOf = (text) => {
  const m = /(\d{2})\.(\d{2})\.(\d{4})/.exec(String(text));
  return m ? `${m[3]}-${m[2]}-${m[1]}` : null;
};

/**
 * Opens the reporting system the way a person does: the services page, then a click on the service's card. The site
 * opens it in a new tab; an informational notice may cover the page first and is closed if it has only a close button.
 *
 * @returns the page of the reporting system
 */
export async function openReporting(context, page, entryText, say = async () => {}) {
  await say('progress', 'Opening the e-reporting system');
  await page.goto(`${PORTAL_ORIGIN}/with-sidebar/services`, { waitUntil: 'domcontentloaded', timeout: 45_000 });
  await settle(page);

  const popups = [];
  context.on('page', (p) => popups.push(p));

  const card = page.locator('a[href*="wefo4-clientui"]').filter({ hasText: entryText }).first();
  if (!(await card.count())) throw new NotMapped(`the e-reporting service card "${entryText}" on the services page`);
  await card.click({ timeout: 10_000 });

  const deadline = Date.now() + 40_000;
  while (Date.now() < deadline) {
    for (const p of [page, ...popups]) {
      if (p.isClosed()) continue;
      if (isReportingOpen(p.url())) {
        await settle(p);
        return p;
      }
      await dismissNotice(p);
    }
    await page.waitForTimeout(500);
  }
  throw new Error('The e-reporting system did not open within 40 seconds.');
}

/**
 * Reads every pane of the journal. Each row keeps the cabinet's own words (name, period, state) next to what Bugalter
 * makes of them; anything not recognised stays null instead of being guessed.
 */
export async function readJournal(page, { formTypes = {}, entity = 'individual' } = {}) {
  await page.locator('#div_approved_reports').waitFor({ state: 'attached', timeout: 20_000 });

  const rows = [];
  for (const [pane, status] of Object.entries(PANES)) {
    const table = await readTable(page, { table: `#${pane} table`, columns: COLUMNS });

    for (const row of table) {
      const period = periodOf(row.period, row.year);
      rows.push({
        pane,
        report_number: /^\d+$/.test(row.report_id.trim()) ? row.report_id.trim() : null,
        form: row.form.replace(/\s+/g, ' ').trim(),
        year: /^\d{4}$/.test(row.year.trim()) ? row.year.trim() : null,
        period_text: row.period.replace(/\s+/g, ' ').trim(),
        state_text: row.state.replace(/\s+/g, ' ').trim(),
        sent_at: dateOf(row.sent_at),
        type: typeOf(row.form, formTypes),
        period_start: period?.start ?? null,
        period_end: period?.end ?? null,
        status,
        entity,
      });
    }
  }

  return rows;
}

/** The snapshot Laravel expects (PortalSnapshot::normalize makes it safe again on its side). */
export function toSnapshot(rows, identity) {
  return {
    taxpayer: { tin: identity.tin, name: identity.name ?? null },
    reports: rows.map((r) => ({
      type: r.type,
      form: r.form,
      name: r.form,
      period_start: r.period_start,
      period_end: r.period_end,
      status: r.status,
      submitted_at: r.sent_at,
      receipt: r.report_number,
    })),
    balances: [],
    messages: [],
  };
}
